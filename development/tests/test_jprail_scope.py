class OfficialScopeControls(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.passes={p['id']:p for p in json.loads((DATA/'passes.json').read_text())['passes']}
        cls.stations=json.loads((DATA/'stations.json').read_text())
        cls.network=json.loads((DATA/'network-detail.geojson').read_text())['features']
        cls.ranges=json.loads((DATA/'pass-ranges-detail.json').read_text())

    def features(self,id):
        p=self.passes[id];r=self.ranges.get(id);features=[]
        replaced={(f['properties']['operator'],f['properties']['name']) for f in r['features']} if r else set()
        for f in self.network:
            q=f['properties']
            if (q['operator'],q['name']) in replaced:continue
            if any(q['operator'] in s['operators'] and ('kinds' not in s or q['kind'] in s['kinds']) and ('lineNames' not in s or q['name'] in s['lineNames']) and not any(n in q['name'] for n in s.get('exclude',[])) for s in p['selectors']):features.append(f)
        return features+(r['features'] if r else [])

    def test_each_product_has_independent_inside_and_outside_controls(self):
        controls=[line.split('|') for line in CONTROLS.splitlines()]
        self.assertEqual({c[0] for c in controls},set(self.passes))
        for id,inside,outside in controls:
            fs=self.features(id)
            for check,expected in [(inside,True),(outside,False)]:
                with self.subTest(id=id,check=check,expected=expected):
                    op,line,name=check.split('/');op=OPS.get(op,op)
                    stations=[s for s in self.stations if s[0]==name and s[3]==op and s[4]==line]
                    self.assertTrue(stations,'control must resolve against the source station library')
                    paths=[shape(f['geometry']) for f in fs if f['properties']['operator']==op and f['properties']['name']==line]
                    covered=bool(paths) and min(unary_union(paths).distance(Point(s[2],s[1])) for s in stations)<.003
                    self.assertEqual(covered,expected)

    def test_repaired_corridors_preserve_every_original_segment(self):
        fs=self.features('hokuriku-arch')
        for op,line in [('東日本旅客鉄道','大糸線'),('西日本旅客鉄道','大糸線'),('西日本旅客鉄道','小浜線'),('西日本旅客鉄道','舞鶴線')]:
            with self.subTest(operator=op,line=line):
                source=unary_union([shape(f['geometry']) for f in self.network if f['properties']['operator']==op and f['properties']['name']==line])
                actual=unary_union([shape(f['geometry']) for f in fs if f['properties']['operator']==op and f['properties']['name']==line])
                self.assertLess(source.difference(actual.buffer(.00001)).length,.0001,'whole source corridor, not a chord or sampled station list')
        for id in ['hokuriku-arch','east-hokkaido']:
            for file in ['pass-ranges.json','pass-ranges-detail.json']:
                ranges=json.loads((DATA/file).read_text())[id]
                self.assertTrue({'東日本旅客鉄道|総武線|四街道','東日本旅客鉄道|総武線|佐倉'}<=set(ranges['stationKeys']))
                self.assertTrue('東日本旅客鉄道|東海道線|羽沢横浜国大' in ranges['stationKeys'])

@unittest.skipUnless(importlib.util.find_spec('playwright'),'Playwright required')
class OverviewMaps(unittest.TestCase):
    def test_all_products_paint_the_final_overview_geometry(self):
        import functools
        import threading
        from http.server import SimpleHTTPRequestHandler,ThreadingHTTPServer
        from urllib.parse import urlsplit
        from playwright.sync_api import sync_playwright
        from development.tests.test_jprail_audit import RenderedCatalogue
        class Handler(SimpleHTTPRequestHandler):
            def log_message(self,*args):pass
        server=ThreadingHTTPServer(('127.0.0.1',0),functools.partial(Handler,directory=str(DATA.parents[2])))
        threading.Thread(target=server.serve_forever,daemon=True).start()
        records=[];errors=[]
        try:
            with sync_playwright() as pw:
                browser=pw.chromium.launch(channel='chrome',headless=True)
                context=browser.new_context(viewport={'width':1600,'height':1040},reduced_motion='reduce')
                context.route('**/*',lambda r:r.continue_() if urlsplit(r.request.url).hostname=='127.0.0.1' else r.abort())
                page=context.new_page();page.on('pageerror',lambda e:errors.append(str(e)))
                page.goto(f'http://127.0.0.1:{server.server_port}/JPRail.html',wait_until='domcontentloaded')
                page.wait_for_function('window.JPRail?.state.stations.length>10000')
                page.locator('#showEnded').check()
                checker=RenderedCatalogue('test_every_pass_and_continuous_zoom')
                ids=page.evaluate('JPRail.state.passes.map(p=>p.id)');self.assertEqual(len(ids),55)
                for id in ids:
                    with self.subTest(id=id):
                        page.locator('[data-pass="'+id+'"]').click();page.wait_for_function('JPRail.camera.whenIdle()')
                        # Visit a real railway point, not a possibly empty box centre.
                        point=page.evaluate('''()=>{const f=JPRail.state.displayed[0],lines=f.geometry.type==='LineString'?[f.geometry.coordinates]:f.geometry.coordinates,line=lines.reduce((a,b)=>a.length>b.length?a:b);return line[Math.floor(line.length/2)];}''')
                        for zoom in [4,8]:
                            page.evaluate('([p,z])=>JPRail.camera.setView([p[1],p[0]],z)',[point,zoom]);page.wait_for_function('JPRail.camera.whenIdle()')
                            self.assertEqual(page.evaluate('JPRail.state.detailStatus'),'overview')
                            checker.check_rendered_layers(page);checker.check_labels(page)
                        # At regional zoom short private railways can be entirely
                        # beneath station labels. Inspect the actual route buffer
                        # too, instead of demanding unoccluded segment samples.
                        page.evaluate('()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))')
                        pixels=page.evaluate('''()=>{
                          const colors=[...new Set(JPRail.state.displayed.map(f=>JPRail.railStyle(f).color))].map(c=>[1,3,5].map(i=>parseInt(c.slice(i,i+2),16)));
                          let count=0;
                          for(const canvas of JPRail.map.getPane('railRoutes').querySelectorAll('canvas')){
                            const data=canvas.getContext('2d').getImageData(0,0,canvas.width,canvas.height).data;
                            for(let i=0;i<data.length;i+=4)if(data[i+3]>220&&colors.some(c=>c.every((v,j)=>Math.abs(v-data[i+j])<8)))count++;
                          }return count;
                        }''')
                        self.assertGreater(pixels,10,'matched railway must actually paint its original colour')
                        samples=checker.check_paint(page)
                        records.append({'id':id,'views':2,'paintSamples':samples,'coloredPixels':pixels})
                self.assertEqual(errors,[])
                context.close()
        finally:server.shutdown();server.server_close()
        if os.environ.get('JPRAIL_OVERVIEW_OUTPUT'):Path(os.environ['JPRAIL_OVERVIEW_OUTPUT']).write_text(json.dumps(records,ensure_ascii=False))
        print('final overview:',len(records),'products;',sum(r['paintSamples'] for r in records),'railway samples')

if __name__=='__main__':unittest.main()
