const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {chromium}=require('playwright');
(async()=>{
    const browser=await chromium.launch({headless:true,...(process.env.TEST_BROWSER_CHANNEL?{channel:process.env.TEST_BROWSER_CHANNEL}:{})});
    try{
        const context=await browser.newContext({viewport:{width:1512,height:1100},acceptDownloads:true});
        const root=process.cwd(),errors=[];
        await context.route('**/*',async route=>{
            const url=new URL(route.request().url());if(url.origin!=='http://127.0.0.1:14331')return route.abort();
            const file=path.resolve(root,'.'+url.pathname);
            if(!file.startsWith(root+path.sep)||!fs.existsSync(file))return route.fulfill({status:404,body:''});
            return route.fulfill({path:file});
        });
        const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
        await page.goto('http://127.0.0.1:14331/simulator.html');
        const ready=async()=>page.waitForFunction(()=>window.Simulator?.getState().frame&&!Simulator.getState().busy,{},{timeout:60000});
        await ready();assert.equal(await page.locator('#station-select option').count(),160);
        assert.equal(await page.locator('.map-card').count(),2);
        await page.locator('[data-time="23.5"]').click();await ready();
        assert.equal(await page.evaluate(()=>Simulator.getState().frame.t),23.5);
        await page.locator('#view-prd').click();
        await page.screenshot({path:'/private/tmp/simulator-desktop.png',fullPage:true});
        const initial=await page.evaluate(()=>Simulator.getState().frame.observations['59493']);
        await page.locator('#reset').click();await ready();
        await page.locator('[data-time="23.5"]').click();await ready();
        assert.deepEqual(await page.evaluate(()=>Simulator.getState().frame.observations['59493']),initial,'rewind must replay same fields');
        await page.locator('[data-layout="4"]').click();assert.equal(await page.locator('.map-card').count(),4);
        await page.locator('.map-card select').nth(0).selectOption('reflectivity');
        await page.locator('.map-card select').nth(1).selectOption('velocity');
        await page.locator('.map-card select').nth(2).selectOption('lowwind');
        await page.locator('.map-card select').nth(3).selectOption('upperwind');
        assert.deepEqual(await page.locator('.map-time').allTextContents(),Array(4).fill(await page.locator('#sim-clock').innerText()));
        await page.locator('#station-search').fill('59488');await page.locator('#station-select').selectOption('59488');await ready();
        assert.equal(await page.locator('#station-name').innerText(),'珠海');
        await page.locator('#station-radar').click();assert.match(await page.locator('#radar-name').innerText(),/珠海/);
        await page.locator('.custom-station summary').click();
        await page.locator('#custom-name').fill('珠江口试验点');await page.locator('#custom-lon').fill('113.74');await page.locator('#custom-lat').fill('22.55');
        await page.locator('#station-form button[type=submit]').click();await ready();
        assert.equal(await page.locator('#station-name').innerText(),'珠江口试验点');
        assert.equal(await page.evaluate(()=>Simulator.getState().stationCount),161);
        assert.ok(await page.evaluate(()=>Simulator.getState().series.length>200),'late-added point gets full reconstructed history');
        assert.equal(await page.evaluate(()=>Simulator.getState().series[0].total),0);
        const downloadPromise=page.waitForEvent('download');await page.locator('#export-station').click();const download=await downloadPromise;
        const exported=fs.readFileSync(await download.path(),'utf8');assert.match(exported,/TEACHING SIMULATION ONLY/);assert.match(exported,/珠江口试验点/);
        await page.locator('#no-estuary').click();await ready();assert.equal(await page.evaluate(()=>Simulator.getState().frame.p.estuary),0);
        assert.equal(await page.locator('#estuary-loss').innerText(),'0%');
        await page.locator('#restore-parameters').click();await ready();
        await page.locator('[data-time="71"]').click();await ready();
        await page.screenshot({path:'/private/tmp/simulator-four-panels.png',fullPage:true});
        await page.locator('#play').click();await page.waitForTimeout(1200);await page.locator('#play').click();await ready();
        assert.ok(await page.evaluate(()=>Simulator.getState().frame.t>71));
        await page.setViewportSize({width:390,height:844});await page.locator('[data-layout="2"]').click();
        await page.screenshot({path:'/private/tmp/simulator-mobile.png',fullPage:true});
        assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'mobile must not overflow horizontally');
        await page.reload();await ready();assert.equal(await page.evaluate(()=>Simulator.getState().stationCount),161,'custom points survive reload');
        await page.locator('#station-search').fill('珠江口试验点');const id=await page.locator('#station-select option').first().getAttribute('value');
        await page.locator('#station-select').selectOption(id);await ready();await page.locator('#delete-station').click();await ready();
        assert.equal(await page.evaluate(()=>Simulator.getState().stationCount),160);
        assert.deepEqual(errors,[]);
        console.log('PASS: synchronized selectable maps, worker replay, 160 stations, custom point persistence/history/deletion, CSV, controls, playback and mobile layout.');
    }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
