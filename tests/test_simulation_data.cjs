const assert=require('node:assert/strict');
const D=require('../assets/scripts/simulation-data.js');
const g={nx:3,ny:2,west:113,south:22,dlon:.1,dlat:.1,nominal_km:4,z_agl_m:[30,500,1500]};
const m={schema:2,status:'complete',simulation:true,grid:g,frames:[{hour:0,file:'frame-0000.json.gz',sha256:'a'.repeat(64)}]};
assert.equal(D.validateManifest(m),m);
assert.throws(()=>D.validateManifest({...m,frames:[{hour:0,file:'../secret',sha256:'a'.repeat(64)}]}));
assert.throws(()=>D.validateManifest({...m,status:'running'}));
const packet={shape:[2,3],scale:.5,offset:10,data:Buffer.from(new Int16Array([0,2,4,6,8,32767]).buffer).toString('base64')};
const f=D.unpack(packet,g);assert.equal(D.value(f,1),11);assert.ok(Number.isNaN(D.value(f,5)));assert.equal(D.index(g,0,0),-1);
assert.equal(D.index(g,113.1,22.1),4);assert.throws(()=>D.unpack({...packet,data:'AA=='},g));
const zero={...f,data:new Int16Array(6),offset:0,scale:1};
const volume=v=>({shape:[3,2,3],scale:1,offset:0,data:new Int16Array(18).fill(v)});
const fields={terrain:zero,dbz3:volume(40),u3:volume(10),v3:volume(0),w3:volume(0)};
const east=D.radar(fields,g,113.1,22,{lon:112.9,lat:22},1.5),west=D.radar(fields,g,113.1,22,{lon:113.3,lat:22},1.5);
assert.ok(east.valid&&west.valid&&east.velocity>0&&west.velocity<0);
const ice=D.radar({...fields,fall3:volume(1),echo_u3:volume(5)},g,113.1,22,{lon:112.9,lat:22},1.5);
const iceExpected=5*Math.cos(1.5*Math.PI/180)-Math.sin(1.5*Math.PI/180);
assert.ok(Math.abs(ice.velocity-iceExpected)<1e-9,'radar must use reflectivity-weighted drift and particle fall speed');
assert.equal(D.radar({...fields,dbz3:volume(-10)},g,113.1,22,{lon:112.9,lat:22},1.5).valid,false);
console.log('PASS: v2 manifest, path safety, packed fields, missing data, grid sampling and Doppler geometry');
